# Probe an NVIDIA open-gpu-kernel-modules tree and write the configuration
# header libmc is compiled with (the Makefile force-includes it).
#
# The RM/UVM ioctl interface is private, and its structs change between
# driver releases.  Compiling against the release's own headers gets the
# layouts right.  What compiling alone cannot absorb is a source-level
# difference -- a field that exists in one release and not another -- and
# each such difference becomes a feature probe here, never a version
# comparison.  This is the approach of the NVIDIA kernel module's own
# conftest.sh for kernel versions.  To handle a new difference, add one
# probe below and one #if on its macro at the point of use.
#
# The header also records the tree's release string, which the strict RM
# version handshake (NV_ESC_CHECK_VERSION_STR) must match at run time.
#
# Usage: nvidia_conftest.sh NVIDIA_SRC OUT_HEADER CC [-I...]
#
# OUT_HEADER is replaced only when its contents change, so objects that
# depend on it rebuild only when the driver tree does.
set -euo pipefail
if [[ $# -lt 3 ]]; then
    echo "usage: $0 NVIDIA_SRC OUT_HEADER CC [-I...]" >&2
    exit 2
fi
src=$1 out=$2 cc=$3
shift 3
incs=("$@")

version=$(sed -n 's/^NVIDIA_VERSION[[:space:]]*=[[:space:]]*//p' \
          "$src/version.mk" 2>/dev/null | head -n 1)
if [[ ! "$version" =~ ^[0-9]+(\.[0-9]+)+$ ]]; then
    echo "nvidia_conftest: no NVIDIA release number in $src/version.mk" >&2
    exit 1
fi

outdir=$(dirname -- "$out")
mkdir -p "$outdir"
tmp=$(mktemp -d "$outdir/.conftest.XXXXXX")
trap 'rm -rf "$tmp"' EXIT

compiles() {
    printf '%s\n' "$1" > "$tmp/probe.c"
    "$cc" -std=gnu11 -fsyntax-only "${incs[@]}" "$tmp/probe.c" 2> "$tmp/err"
}

# Every probe starts from these headers.  If they alone fail to compile, the
# include path is wrong and every probe would silently report "absent", so
# that is a hard error rather than a configuration.
base='#include "nvtypes.h"
#include "nvos.h"
#include "alloc/alloc_channel.h"'
if ! compiles "$base
NV_CHANNEL_ALLOC_PARAMS mc_probe;"; then
    echo "nvidia_conftest: the base probe does not compile against $src:" >&2
    cat "$tmp/err" >&2
    exit 1
fi

probe() {  # MACRO DESCRIPTION CODE
    local value=0
    if compiles "$base
$3"; then value=1; fi
    printf '/* %s */\n#define %s %s\n' "$2" "$1" "$value"
}

{
    printf '/* Generated by tools/nvidia_conftest.sh from NVIDIA %s.  Do not edit. */\n' "$version"
    printf '#ifndef MC_NV_CONFIG_H\n#define MC_NV_CONFIG_H\n\n'
    printf '/* Release the strict RM version handshake must match exactly. */\n'
    printf '#define MC_NVIDIA_DRIVER_VERSION "%s"\n\n' "$version"
    probe MC_NV_HAVE_CHANNEL_HANDLE_VASPACE \
        "NV_CHANNEL_ALLOC_PARAMS.hHandleVASpace: present in 610.43.02, absent in 595.99.02" \
        'int mc_probe = sizeof(((NV_CHANNEL_ALLOC_PARAMS *)0)->hHandleVASpace);'
    printf '\n#endif /* MC_NV_CONFIG_H */\n'
} > "$tmp/config.h"

if ! cmp -s "$tmp/config.h" "$out"; then
    cp "$tmp/config.h" "$out"
    echo "  CONFIG  $out (NVIDIA $version)"
fi
